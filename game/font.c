void font_draw(SDL_Renderer *r, const char *s, int x, int y, int cell) {
    SDL_Rect rc[256];
    int n = 0;
    for (; *s; s++, x += 6 * cell) {
        int c = toupper((unsigned char)*s), gi = -1;
        if (c >= 'A' && c <= 'Z') gi = c - 'A';
        else if (c >= '0' && c <= '9') gi = 26 + c - '0';
        if (gi < 0) continue;
        for (int row = 0; row < 7; row++)
            for (int col = 0; col < 5; col++)
                if (G[gi][row] & (0x10 >> col)) {
                    rc[n].x = x + col * cell; rc[n].y = y + row * cell;
                    rc[n].w = cell;           rc[n].h = cell;
                    if (++n == 256) { SDL_RenderFillRects(r, rc, n); n = 0; }
                }
    }
    if (n) SDL_RenderFillRects(r, rc, n);
}

int font_width(const char *s, int cell) {
    int n = (int)strlen(s);
    return n ? n * 6 * cell - cell : 0;
}

int font_height(int cell) { return 7 * cell; }
